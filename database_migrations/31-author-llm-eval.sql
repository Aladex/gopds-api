-- The eval run inside the service (design K, phase 3). Migration 29 has the
-- run, job and eval tables; this file lets the eval run measure the
-- participants' fingerprints through the ordinary job path, and gives a run
-- its own settings.
--
--   * A job purpose eval_fingerprint and an eval item set fingerprint: the
--     fixed fingerprint request is frozen as an eval item, and the fingerprint
--     stage sends it to every participant as ordinary jobs, so the calls are
--     leased, budgeted and recorded like every other.
--   * author_llm_run.settings: what a run was started with — the output mode
--     of every participant and the batch sizes the candidates are compared at.
--     Written with the run and never changed.
--   * author_llm_eval_skip: every item an eval run left out — an input that
--     cannot be sent, an excerpt that does not read, an incomplete anchor
--     set — with its identifiers and a closed reason, so the report shows it
--     and the stage moves on.
--
-- (Migration 30 is another branch's; this one is 31.)
--
-- Locks: the three tables are taken up front, NOWAIT. They are the LLM
-- worker's; a worker holding one makes the file fail at once, its rollback
-- releases whatever it had taken, and the next start retries the file whole.

SET LOCAL lock_timeout = '5s';

LOCK TABLE public.author_llm_run, public.author_llm_job, public.author_llm_eval_item
    IN ACCESS EXCLUSIVE MODE NOWAIT;

ALTER TABLE public.author_llm_job
    DROP CONSTRAINT author_llm_job_purpose_check,
    ADD CONSTRAINT author_llm_job_purpose_check
        CHECK (purpose IN ('review', 'swap_check', 'eval_judge', 'eval_candidate', 'eval_repeat',
                           'eval_anchor', 'eval_fingerprint', 'canary'));

ALTER TABLE public.author_llm_eval_item
    DROP CONSTRAINT author_llm_eval_item_set_check,
    ADD CONSTRAINT author_llm_eval_item_set_check
        CHECK (item_set IN ('holdout', 'dev', 'anchor', 'canary', 'fingerprint'));

-- Not in the run's list of mutable columns (migration 29), so the identity
-- trigger keeps it as written.
ALTER TABLE public.author_llm_run
    ADD COLUMN settings JSONB NOT NULL DEFAULT '{}'::jsonb,
    ADD CONSTRAINT author_llm_run_settings_check CHECK (jsonb_typeof(settings) = 'object');

CREATE TABLE public.author_llm_eval_skip (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             BIGINT NOT NULL REFERENCES public.author_llm_run (id) ON DELETE RESTRICT,
    stage              TEXT NOT NULL,
    reason             TEXT NOT NULL,
    -- The set the item was left out of, for the freeze; a later run that
    -- reuses the set reports the skips with it.
    set_version        TEXT,
    source_fingerprint BYTEA,
    eval_item_id       BIGINT REFERENCES public.author_llm_eval_item (id) ON DELETE RESTRICT,
    book_id            BIGINT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT author_llm_eval_skip_stage_check CHECK (stage ~ '^[a-z][a-z_]{0,31}$'),
    CONSTRAINT author_llm_eval_skip_reason_check CHECK (reason ~ '^[a-z][a-z0-9_]{0,63}$'),
    CONSTRAINT author_llm_eval_skip_fingerprint_check
        CHECK (source_fingerprint IS NULL OR octet_length(source_fingerprint) = 32)
);

-- One record per run, reason and item: a freeze retried after a crash does
-- not record a skip twice.
CREATE UNIQUE INDEX author_llm_eval_skip_once
    ON public.author_llm_eval_skip (run_id, reason, coalesce(set_version, ''),
        coalesce(source_fingerprint, ''::bytea), coalesce(eval_item_id, 0), coalesce(book_id, 0));
CREATE INDEX author_llm_eval_skip_set_idx ON public.author_llm_eval_skip (set_version) WHERE set_version IS NOT NULL;

CREATE TRIGGER author_llm_eval_skip_immutable
    BEFORE UPDATE OR DELETE ON public.author_llm_eval_skip
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_mutation();
