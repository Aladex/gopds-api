-- A participant the provider switches mid-run (another model behind the same
-- name) fails its periodic fingerprint check and is paused for drift. The
-- admin's resume re-learns its fingerprint in the current run: the fixed
-- request repeated until the calls agree, the output mode negotiated again,
-- and the new reference used from then on. author_llm_relearn keeps every
-- re-learn of a run — the old and the new reference, the mode, when, and why
-- one did not settle — for the run's checks and its report.
--
-- A re-learn that does not settle (the calls disagree, or no output mode
-- works) leaves the participant paused: relearn_unstable.
--
-- Locks: the participants' state is taken up front, NOWAIT, and the runs in
-- the mode the new foreign key needs, as in 28-34. A worker holding either
-- makes the file fail at once; the next start retries it whole.

SET LOCAL lock_timeout = '5s';

LOCK TABLE public.author_llm_provider_state IN ACCESS EXCLUSIVE MODE NOWAIT;
LOCK TABLE public.author_llm_run IN SHARE ROW EXCLUSIVE MODE NOWAIT;

ALTER TABLE public.author_llm_provider_state
    DROP CONSTRAINT author_llm_provider_state_pause_check,
    ADD CONSTRAINT author_llm_provider_state_pause_check
        CHECK ((paused_reason IS NULL) = (paused_at IS NULL)
               AND (paused_reason IS NULL
                    OR paused_reason IN ('auth', 'model_mismatch', 'bad_request', 'drift', 'over_reserve',
                                         'relearn_unstable')));

-- One re-learn of one participant in one run. relearning: the checks are
-- being sent (in output_mode, repeats of them must agree); learned: the new
-- reference (and the model ids the calls named) replaces the old one for the
-- rest of the run; unstable: it did not settle, and why. reasoning is whether
-- the participant reasons (its reference then carries a reasoning floor).
CREATE TABLE public.author_llm_relearn (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT NOT NULL REFERENCES public.author_llm_run (id) ON DELETE RESTRICT,
    config_version TEXT NOT NULL,
    slot           TEXT NOT NULL,
    status         TEXT NOT NULL DEFAULT 'relearning',
    repeats        SMALLINT NOT NULL,
    reasoning      BOOLEAN NOT NULL,
    output_mode    TEXT NOT NULL,
    old_reference  JSONB NOT NULL,
    new_reference  JSONB,
    models         JSONB,
    reason         TEXT,
    started_at     TIMESTAMPTZ NOT NULL,
    finished_at    TIMESTAMPTZ,

    CONSTRAINT author_llm_relearn_participant_fkey
        FOREIGN KEY (config_version, slot)
        REFERENCES public.author_llm_participant (config_version, slot) ON DELETE RESTRICT,
    CONSTRAINT author_llm_relearn_status_check CHECK (status IN ('relearning', 'learned', 'unstable')),
    CONSTRAINT author_llm_relearn_repeats_check CHECK (repeats BETWEEN 1 AND 20),
    CONSTRAINT author_llm_relearn_mode_check CHECK (output_mode IN ('json_schema', 'json_object', 'tool')),
    CONSTRAINT author_llm_relearn_reference_check
        CHECK (jsonb_typeof(old_reference) = 'object'
               AND (status = 'learned') = (new_reference IS NOT NULL AND jsonb_typeof(new_reference) = 'object')
               AND (status = 'learned') = (models IS NOT NULL AND jsonb_typeof(models) = 'array')),
    CONSTRAINT author_llm_relearn_reason_check
        CHECK ((status = 'unstable') = (reason IS NOT NULL)
               AND (reason IS NULL OR reason ~ '^[a-z][a-z_]{0,31}:[ -~]{0,200}$')),
    CONSTRAINT author_llm_relearn_finished_check
        CHECK ((status = 'relearning') = (finished_at IS NULL) AND (finished_at IS NULL OR finished_at >= started_at))
);

CREATE UNIQUE INDEX author_llm_relearn_one_open ON public.author_llm_relearn (run_id, slot) WHERE status = 'relearning';
CREATE INDEX author_llm_relearn_run_idx ON public.author_llm_relearn (run_id, slot, id);

-- What a re-learn measured and decided is fixed once it ended.
CREATE TRIGGER author_llm_relearn_identity
    BEFORE UPDATE OR DELETE ON public.author_llm_relearn
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_mutation(
        'status', 'output_mode', 'new_reference', 'models', 'reason', 'finished_at');

CREATE TRIGGER author_llm_relearn_finished
    BEFORE UPDATE ON public.author_llm_relearn
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_finished();
