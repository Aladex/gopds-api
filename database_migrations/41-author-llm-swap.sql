-- Swaps among the automatically selected names (design K, phase 7). About 8%
-- of the structured_person credits policy v2 selected have given and family
-- name the other way round in the FB2 itself. The catalog's own role
-- statistics find the candidates without an LLM; an eval run of mode swap
-- measures the (swap, script) strata with the same gates as any other; a swap
-- run asks the production pair and both judges about the candidates, and an
-- answer is applied — a new LLM result of class llm.swap selected over the
-- local one, through the resolver and its audit — only when the pair agrees,
-- both judges confirm it and the statistics agree (decision 8).
--
--   * author_token_role_snapshot / author_token_role_stats — the role
--     statistics: for every token (its search key) how many current
--     structured_person author credits hold it in the first, the middle and
--     the last field. Recomputed by every run that needs it (a swap run, an
--     eval of mode swap), one snapshot per run, kept for the audit; immutable.
--   * author_llm_run mode swap for an eval run: the full measurement of the
--     swap strata alone, so the initials strata are not paid for again.
--   * Two outcomes of a swap verdict that change nothing: swap_fields_confirmed
--     (the pair confirms the FB2 fields: nothing to swap) and
--     swap_stats_disagree (the statistics do not say the same as the models).
--
-- Locks: the runs and the verdicts are taken up front, NOWAIT, like 28-40. A
-- worker holding either makes the file fail at once; the next start retries
-- it whole.

SET LOCAL lock_timeout = '5s';

LOCK TABLE public.author_llm_run, public.author_llm_verdict IN ACCESS EXCLUSIVE MODE NOWAIT;

ALTER TABLE public.author_llm_run
    DROP CONSTRAINT author_llm_run_mode_check,
    ADD CONSTRAINT author_llm_run_mode_check
        CHECK (CASE kind WHEN 'eval' THEN mode IN ('dev', 'pilot', 'full', 'swap') ELSE mode IN ('pilot', 'full') END);

ALTER TABLE public.author_llm_verdict
    DROP CONSTRAINT author_llm_verdict_outcome_check,
    ADD CONSTRAINT author_llm_verdict_outcome_check
        CHECK (outcome_reason IS NULL
               OR outcome_reason IN ('llm_disagreement', 'llm_refused', 'llm_invalid', 'llm_failed',
                                     'llm_judge_disagreement', 'llm_judge_refused', 'llm_judge_invalid',
                                     'llm_judge_failed', 'llm_not_registered', 'llm_context_unavailable',
                                     'apply_failed', 'input_gone', 'swap_fields_confirmed',
                                     'swap_stats_disagree'));

-- One computation of the role statistics, by the run that needed it.
CREATE TABLE public.author_token_role_snapshot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id     BIGINT NOT NULL REFERENCES public.author_llm_run (id) ON DELETE RESTRICT,
    -- How many credits and distinct tokens the statistics were counted over.
    credits    INTEGER NOT NULL,
    tokens     INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT author_token_role_snapshot_run_key UNIQUE (run_id),
    CONSTRAINT author_token_role_snapshot_counts_check CHECK (credits >= 0 AND tokens >= 0)
);

CREATE TRIGGER author_token_role_snapshot_immutable
    BEFORE UPDATE OR DELETE ON public.author_token_role_snapshot
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_mutation();

-- A token's counts in one snapshot. The token is the search key of a word of
-- a name field, as the request tokenizes it.
CREATE TABLE public.author_token_role_stats (
    snapshot_id  BIGINT NOT NULL REFERENCES public.author_token_role_snapshot (id) ON DELETE RESTRICT,
    token        TEXT NOT NULL,
    first_count  INTEGER NOT NULL,
    middle_count INTEGER NOT NULL,
    last_count   INTEGER NOT NULL,

    PRIMARY KEY (snapshot_id, token),
    CONSTRAINT author_token_role_stats_token_check CHECK (token <> '' AND char_length(token) <= 256),
    CONSTRAINT author_token_role_stats_counts_check
        CHECK (first_count >= 0 AND middle_count >= 0 AND last_count >= 0
               AND first_count + middle_count + last_count > 0)
);

CREATE TRIGGER author_token_role_stats_immutable
    BEFORE UPDATE OR DELETE ON public.author_token_role_stats
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_mutation();
