-- 60: Wikidata as evidence of the author entity build (design E, phase E4w).
--
--   * wikidata_extract — one fetch of the reference data: numbered as it
--     starts, published under its content ID (wikidata.Manifest.ContentID)
--     once every chunk is in; the build reads the newest published extract,
--     and only it is kept. A fetch whose content the published extract
--     already has is discarded: the same data is never published twice.
--   * wikidata_extract_chunk — the chunks a fetch has written, each in its
--     own transaction with its rows: a failed chunk is redone alone, and a
--     fetch started again goes on from the chunks it lacks.
--   * wikidata_person, wikidata_name, wikidata_work — the people, their names
--     (labels, aliases, pseudonyms P742, names in their native language
--     P1559) keyed by public.search_normalize like the entity names, and
--     their notable works (P800) by normalized title. Labels, years and
--     works keep their text and QIDs: a later author page reads an item by
--     its QID without another import.
--   * author_entity_reference — an entity's Wikidata item, kept by the build.
--   * author_entity_assignment and author_entity_merge_log take the method
--     "evidence" (a Wikidata merge is evidence, like D3's books), and the
--     rules of both assignment tables take "wikidata:<QID>@<extract>".
--
-- No backfill: an administrator fetches the first extract.
--
-- Locks: the assignment tables and the merge log, up front, NOWAIT, like
-- 56-58: a running entity build makes this fail at once, and the next start
-- applies it whole. The new tables are empty.

SET LOCAL lock_timeout = '5s';

LOCK TABLE public.author_entity_assignment, public.author_entity_credit_assignment, public.author_entity_merge_log
    IN ACCESS EXCLUSIVE MODE NOWAIT;
-- The reference's foreign key reads the entities: no build may write them
-- meanwhile.
LOCK TABLE public.author_entity IN SHARE ROW EXCLUSIVE MODE NOWAIT;

ALTER TABLE public.author_entity_assignment
    DROP CONSTRAINT author_entity_assignment_method_check,
    ADD CONSTRAINT author_entity_assignment_method_check CHECK (method IN ('deterministic', 'evidence', 'model', 'manual')),
    DROP CONSTRAINT author_entity_assignment_rule_check,
    ADD CONSTRAINT author_entity_assignment_rule_check CHECK (rule ~ '^[A-Za-z0-9:+_@-]{1,96}$');

ALTER TABLE public.author_entity_credit_assignment
    DROP CONSTRAINT author_entity_credit_assignment_rule_check,
    ADD CONSTRAINT author_entity_credit_assignment_rule_check CHECK (rule ~ '^[A-Za-z0-9:+_@-]{1,96}$');

ALTER TABLE public.author_entity_merge_log
    DROP CONSTRAINT author_entity_merge_log_method_check,
    ADD CONSTRAINT author_entity_merge_log_method_check CHECK (method IN ('deterministic', 'evidence', 'model', 'manual'));

CREATE TABLE public.wikidata_extract (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id         text,
    status             text NOT NULL DEFAULT 'fetching',
    source             text NOT NULL,
    manifest           jsonb,
    people             integer NOT NULL DEFAULT 0,
    names              integer NOT NULL DEFAULT 0,
    works              integer NOT NULL DEFAULT 0,
    last_error         text,
    -- The pod fetching it, while it does: a fetch whose pod died is taken
    -- over once the lease runs out.
    lease_owner        uuid,
    lease_expires_at   timestamptz,
    created_by_user_id bigint REFERENCES public.auth_user (id) ON DELETE SET NULL,
    started_at         timestamptz NOT NULL DEFAULT now(),
    finished_at        timestamptz,
    -- superseded: a published extract a newer one replaced; abandoned: a
    -- failed one no start resumes any more (a newer extract exists). Their
    -- rows are deleted, the records stay.
    CONSTRAINT wikidata_extract_status_check CHECK (status IN ('fetching', 'failed', 'published', 'duplicate',
        'superseded', 'abandoned')),
    CONSTRAINT wikidata_extract_published_check CHECK (status NOT IN ('published', 'superseded', 'duplicate') OR (content_id IS NOT NULL AND manifest IS NOT NULL)),
    CONSTRAINT wikidata_extract_content_id_check CHECK (content_id IS NULL OR content_id ~ '^wd-[0-9a-f]{16}$'),
    CONSTRAINT wikidata_extract_error_check CHECK (last_error IS NULL OR char_length(last_error) <= 500)
);

-- One fetch at a time, one published extract.
CREATE UNIQUE INDEX wikidata_extract_one_fetching ON public.wikidata_extract ((true)) WHERE status = 'fetching';
CREATE UNIQUE INDEX wikidata_extract_one_published ON public.wikidata_extract ((true)) WHERE status = 'published';

CREATE TABLE public.wikidata_extract_chunk (
    extract_id bigint NOT NULL REFERENCES public.wikidata_extract (id) ON DELETE CASCADE,
    name       text NOT NULL,
    query      text NOT NULL,
    rows       integer NOT NULL,
    skipped    integer NOT NULL,
    sha256     text NOT NULL,
    done_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT wikidata_extract_chunk_pkey PRIMARY KEY (extract_id, name),
    CONSTRAINT wikidata_extract_chunk_sha_check CHECK (sha256 ~ '^[0-9a-f]{64}$')
);

CREATE TABLE public.wikidata_person (
    extract_id bigint NOT NULL REFERENCES public.wikidata_extract (id) ON DELETE CASCADE,
    qid        text NOT NULL,
    born       integer,
    died       integer,
    CONSTRAINT wikidata_person_pkey PRIMARY KEY (extract_id, qid)
);

CREATE TABLE public.wikidata_name (
    extract_id bigint NOT NULL REFERENCES public.wikidata_extract (id) ON DELETE CASCADE,
    key        text NOT NULL,
    qid        text NOT NULL,
    kind       text NOT NULL,
    lang       text NOT NULL DEFAULT '',
    -- The text of a label, in its language, for a later author page that
    -- reads an item by QID; NULL for every other name.
    label      text,
    CONSTRAINT wikidata_name_pkey PRIMARY KEY (extract_id, key, qid, kind, lang),
    CONSTRAINT wikidata_name_kind_check CHECK (kind IN ('label', 'alias', 'pseudonym', 'native')),
    CONSTRAINT wikidata_name_key_check CHECK (key <> '')
);

CREATE INDEX wikidata_name_qid_idx ON public.wikidata_name (extract_id, qid);

CREATE TABLE public.wikidata_work (
    extract_id bigint NOT NULL REFERENCES public.wikidata_extract (id) ON DELETE CASCADE,
    qid        text NOT NULL,
    work_qid   text NOT NULL,
    title_key  text NOT NULL,
    -- The ru/en title as Wikidata labels the work.
    title      text NOT NULL,
    CONSTRAINT wikidata_work_pkey PRIMARY KEY (extract_id, qid, work_qid, title_key),
    CONSTRAINT wikidata_work_title_check CHECK (title_key <> '')
);

CREATE INDEX wikidata_work_title_idx ON public.wikidata_work (extract_id, title_key);

-- An entity's references to the outside: for now its Wikidata item, the one
-- item its names match uniquely (none when they match none, several or only
-- as a pen name). The build keeps it in step with the entity — a survivor
-- takes its group's, a split piece its own — and never touches a pinned
-- row: that is an administrator's decision. One row per source, so a later
-- source is a row, not a column of the entity every search reads.
CREATE TABLE public.author_entity_reference (
    entity_id  uuid NOT NULL REFERENCES public.author_entity (id) ON DELETE CASCADE,
    source     text NOT NULL,
    ref        text NOT NULL,
    -- The extract the reference was read from (wikidata_extract.content_id).
    extract    text NOT NULL DEFAULT '',
    pinned     boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT author_entity_reference_pkey PRIMARY KEY (entity_id, source),
    CONSTRAINT author_entity_reference_source_check CHECK (source IN ('wikidata')),
    CONSTRAINT author_entity_reference_ref_check CHECK (source <> 'wikidata' OR ref ~ '^Q[0-9]{1,12}$')
);

CREATE INDEX author_entity_reference_ref_idx ON public.author_entity_reference (source, ref);
