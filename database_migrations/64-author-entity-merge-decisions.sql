-- 64: merge decisions as entity build input (E4b, plan §4.2, §4.6, §4.11,
-- §5). Nothing here asks a model: decisions come from merge runs (E4d) and
-- from an administrator's revoke; until then the tables stay empty and every
-- pass is what it was.
--
--   * author_entity_merge_decision — "the candidate of this digest is one
--     person" (outcome same) or its revoke (outcome revoked, an
--     administrator's). One live row per digest: a revoke sets revoked_at on
--     the same row and inserts the revoke. A pass applies a same decision only
--     when it generates a candidate of exactly that digest.
--   * author_entity_merge_decision_member — the candidate's member keys when
--     it was decided, so a pass can tell why a decision lapsed.
--   * author_entity_merge_decision_state — what the newest pass did with each
--     decision (applied, lapsed, conflict, and why). Build bookkeeping: no
--     mark, so the build never makes itself due.
--   * author_entity_merge_member — what an entity a model union absorbed held
--     at that moment: the input of its revival (§5.2).
--   * author_entity_revival — each revival's outcome, written when it changes.
--   * author_entity_merge_veto, author_entity_merge_veto_member,
--     author_entity_merge_veto_state — a revoke's durable veto by recorded
--     book and fingerprint (§4.11). Created here so the later sub-phases keep
--     their migration numbers; the build reads them once the veto ships.
--
-- Decisions and vetoes are inputs: a statement that changes one marks a
-- build (author_autopilot_mark). The state tables are not.
--
-- Locks: the new tables reference only each other and get triggers of their
-- own, so this file takes no lock on an existing table and waits for no
-- writer. They are empty.

SET LOCAL lock_timeout = '5s';

CREATE TABLE public.author_entity_merge_decision (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    digest             bytea  NOT NULL,
    -- The merge configuration that asked; NULL for an administrator's
    -- revoke and until the configuration exists (E4c, E4d adds the key).
    config_version     text,
    kind               text   NOT NULL,
    script             text   NOT NULL,
    item_kind          text   NOT NULL,
    credit_id          bigint,
    credit_ordinal     smallint,
    members_sha256     bytea  NOT NULL,
    input_sha256       bytea  NOT NULL,
    outcome            text   NOT NULL,
    source             text   NOT NULL,
    verdict_ids        bigint[] NOT NULL DEFAULT '{}',
    eval_report_id     bigint,
    registration_id    bigint,
    created_at         timestamptz NOT NULL DEFAULT now(),
    created_by_user_id bigint,
    revoked_at         timestamptz,
    revoked_by_user_id bigint,
    CONSTRAINT author_entity_merge_decision_hash_check
        CHECK (octet_length(digest) = 32 AND octet_length(members_sha256) = 32 AND octet_length(input_sha256) = 32),
    CONSTRAINT author_entity_merge_decision_kind_check
        CHECK (kind IN ('bucket', 'swap', 'initials', 'translit')),
    CONSTRAINT author_entity_merge_decision_script_check CHECK (script IN ('Cyrl', 'Latn', 'Cyrl-Latn')),
    CONSTRAINT author_entity_merge_decision_item_check
        CHECK ((item_kind = 'book') = (kind = 'bucket') AND item_kind IN ('entity', 'book')
               AND (item_kind = 'book') = (credit_id IS NOT NULL)
               AND (credit_id IS NULL) = (credit_ordinal IS NULL) AND (credit_ordinal IS NULL OR credit_ordinal >= 0)),
    CONSTRAINT author_entity_merge_decision_outcome_check
        CHECK (outcome IN ('same', 'revoked') AND source IN ('model', 'manual')
               AND (outcome = 'same' OR source = 'manual')),
    -- Only a same decision is revoked; a revoke stays.
    CONSTRAINT author_entity_merge_decision_revoked_check
        CHECK ((revoked_at IS NULL OR outcome = 'same') AND (revoked_at IS NOT NULL OR revoked_by_user_id IS NULL))
);

CREATE UNIQUE INDEX author_entity_merge_decision_live ON public.author_entity_merge_decision (digest)
    WHERE revoked_at IS NULL;

CREATE TABLE public.author_entity_merge_decision_member (
    decision_id        bigint   NOT NULL REFERENCES public.author_entity_merge_decision (id) ON DELETE RESTRICT,
    side               text     NOT NULL,
    source_fingerprint bytea    NOT NULL,
    extractor_version  text     NOT NULL,
    ordinal            smallint NOT NULL,
    CONSTRAINT author_entity_merge_decision_member_pkey
        PRIMARY KEY (decision_id, side, source_fingerprint, extractor_version, ordinal),
    CONSTRAINT author_entity_merge_decision_member_side_check CHECK (side IN ('a', 'b')),
    CONSTRAINT author_entity_merge_decision_member_ordinal_check CHECK (ordinal >= 0)
);

CREATE TABLE public.author_entity_merge_decision_state (
    decision_id  bigint PRIMARY KEY REFERENCES public.author_entity_merge_decision (id) ON DELETE RESTRICT,
    -- The pass that set the state (no foreign key: a reference would lock
    -- the runs a running pass writes).
    build_run_id bigint NOT NULL,
    state        text   NOT NULL,
    reason       text   NOT NULL DEFAULT '',
    CONSTRAINT author_entity_merge_decision_state_check
        CHECK (state IN ('applied', 'lapsed', 'conflict') AND (state = 'applied') = (reason = '')
               AND reason ~ '^[a-z0-9_]{0,64}$')
);

CREATE TABLE public.author_entity_merge_member (
    -- The merge-log row of the absorption (no foreign key, as above).
    merge_log_id       bigint   NOT NULL,
    -- A fingerprint row the entity held, or a credit row.
    source_fingerprint bytea,
    extractor_version  text,
    ordinal            smallint,
    credit_id          bigint,
    credit_ordinal     smallint,
    CONSTRAINT author_entity_merge_member_kind_check
        CHECK ((source_fingerprint IS NULL) = (extractor_version IS NULL)
               AND (source_fingerprint IS NULL) = (ordinal IS NULL)
               AND (credit_id IS NULL) = (credit_ordinal IS NULL)
               AND (source_fingerprint IS NULL) <> (credit_id IS NULL))
);

CREATE INDEX author_entity_merge_member_log_idx ON public.author_entity_merge_member (merge_log_id);

CREATE TABLE public.author_entity_revival (
    build_run_id bigint NOT NULL,
    entity_id    uuid   NOT NULL,
    merge_log_id bigint NOT NULL,
    outcome      text   NOT NULL,
    reason       text   NOT NULL DEFAULT '',
    -- The keys the absorption recorded, those a current credit has, and
    -- those the inheriting entity holds.
    recorded     integer NOT NULL,
    live         integer NOT NULL,
    restored     integer NOT NULL,
    CONSTRAINT author_entity_revival_pkey PRIMARY KEY (build_run_id, entity_id),
    CONSTRAINT author_entity_revival_outcome_check
        CHECK (outcome IN ('exact', 'partial', 'lapsed') AND (outcome = 'exact') = (reason = '')
               AND reason ~ '^[a-z0-9_]{0,64}$'),
    CONSTRAINT author_entity_revival_counts_check
        CHECK (recorded >= 0 AND live >= 0 AND restored >= 0 AND live <= recorded AND restored <= recorded)
);

CREATE INDEX author_entity_revival_entity_idx ON public.author_entity_revival (entity_id, merge_log_id, build_run_id);

CREATE TABLE public.author_entity_merge_veto (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revoke_decision_id bigint NOT NULL REFERENCES public.author_entity_merge_decision (id) ON DELETE RESTRICT,
    item_kind          text   NOT NULL,
    book_id            bigint,
    created_at         timestamptz NOT NULL DEFAULT now(),
    created_by_user_id bigint,
    retired_at         timestamptz,
    retired_by_user_id bigint,
    replaces_veto_id   bigint REFERENCES public.author_entity_merge_veto (id) ON DELETE RESTRICT,
    CONSTRAINT author_entity_merge_veto_item_check
        CHECK (item_kind IN ('entity', 'book') AND (item_kind = 'book') = (book_id IS NOT NULL)),
    CONSTRAINT author_entity_merge_veto_retired_check CHECK (retired_at IS NOT NULL OR retired_by_user_id IS NULL)
);

CREATE TABLE public.author_entity_merge_veto_member (
    veto_id            bigint NOT NULL REFERENCES public.author_entity_merge_veto (id) ON DELETE RESTRICT,
    side               text   NOT NULL,
    -- No foreign key to the book: a deleted book stays recorded, as gone.
    book_id            bigint NOT NULL,
    source_fingerprint bytea  NOT NULL,
    CONSTRAINT author_entity_merge_veto_member_pkey PRIMARY KEY (veto_id, side, book_id, source_fingerprint),
    CONSTRAINT author_entity_merge_veto_member_side_check CHECK (side IN ('a', 'b'))
);

CREATE TABLE public.author_entity_merge_veto_state (
    veto_id              bigint PRIMARY KEY REFERENCES public.author_entity_merge_veto (id) ON DELETE RESTRICT,
    build_run_id         bigint  NOT NULL,
    state                text    NOT NULL,
    held_books           integer NOT NULL,
    lost_books           integer NOT NULL,
    gone_books           integer NOT NULL,
    widened_fingerprints integer NOT NULL,
    CONSTRAINT author_entity_merge_veto_state_check
        CHECK (state IN ('anchored', 'unanchored', 'gone')
               AND held_books >= 0 AND lost_books >= 0 AND gone_books >= 0 AND widened_fingerprints >= 0)
);

-- History rows: a decision is never deleted and changes only by its revoke,
-- once; a veto only by its retirement, once; members never change.
CREATE FUNCTION public.author_entity_merge_history_guard() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    -- TG_ARGV is NULL for a trigger without arguments, and subtracting NULL
    -- would let every change through.
    mutable text[] := coalesce(TG_ARGV, '{}');
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'rows of % are history and cannot be deleted', TG_TABLE_NAME
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF (to_jsonb(OLD) - mutable) IS DISTINCT FROM (to_jsonb(NEW) - mutable) THEN
        RAISE EXCEPTION 'rows of % are history; only % may change', TG_TABLE_NAME, mutable
            USING ERRCODE = 'restrict_violation';
    END IF;
    -- TG_ARGV is zero-based, so look at every mutable column, not an index.
    IF EXISTS (SELECT 1 FROM unnest(mutable) AS c WHERE (to_jsonb(OLD) -> c) <> 'null'::jsonb) THEN
        RAISE EXCEPTION 'rows of % change once: % is set', TG_TABLE_NAME, mutable
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER author_entity_merge_decision_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_decision
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard('revoked_at', 'revoked_by_user_id');
CREATE TRIGGER author_entity_merge_decision_member_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_decision_member
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard();
CREATE TRIGGER author_entity_merge_veto_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_veto
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard('retired_at', 'retired_by_user_id');
CREATE TRIGGER author_entity_merge_veto_member_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_veto_member
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard();

-- Decisions and vetoes are build input. Their members are written in the
-- same transaction as their row, which marks already.
CREATE TRIGGER author_entity_merge_decision_entity_input_insert
    AFTER INSERT ON public.author_entity_merge_decision
    REFERENCING NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
CREATE TRIGGER author_entity_merge_decision_entity_input_update
    AFTER UPDATE ON public.author_entity_merge_decision
    REFERENCING OLD TABLE AS previous NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
CREATE TRIGGER author_entity_merge_veto_entity_input_insert
    AFTER INSERT ON public.author_entity_merge_veto
    REFERENCING NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
CREATE TRIGGER author_entity_merge_veto_entity_input_update
    AFTER UPDATE ON public.author_entity_merge_veto
    REFERENCING OLD TABLE AS previous NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
