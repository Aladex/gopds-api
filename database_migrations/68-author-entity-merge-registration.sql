-- 68: registration of a merge stratum (E4d, plan §4.7). A kind of merge
-- candidate is registered for a merge configuration from a stored merge
-- eval report that passed it; only then do its decisions apply. K's
-- acceptance policy (author_acceptance_class) is not read, written or
-- locked: a merge stratum is not a normalization class.
--
--   * author_entity_merge_registration — (config, kind) registered from a
--     report, cited by id and digest, under the gate judge_consensus (the
--     only truth standard, §3.4). Never deleted; a withdrawal sets
--     withdrawn_at once and is the kill switch of the kind.
--   * author_entity_merge_script_block — one script of a registered kind
--     stops applying (a narrower kill switch, §3.5). Insert only.
--   * author_entity_merge_decision gets its foreign keys: the merge
--     configuration that asked, and the registration it applied under.
--
-- Both tables are build input: a statement that changes one marks a build
-- (author_autopilot_mark), so a withdrawal or a block lands at the next
-- build, and a build past its snapshot is stopped by the fence (§4.9).
--
-- Contested accepts are adjudicated too (coordinator's decision after
-- merge1): a census or holdout item of a merge eval (and merge3's extra
-- Latin questions) the production pair answered same and the judges did
-- not both confirm — no gold — may be labeled like a suite item. The gate
-- counts it an error while it is pending or labeled different; same or
-- unclear clears it. It is never applied either way. One function,
-- author_llm_eval_item_contested, says what a contested accept is; the
-- adjudication trigger and the application's insert both read it. The
-- trigger keeps refusing anything else (an anchor, an uncontested holdout
-- item, K's items).
--
-- Not here (E4d-2): the resolve-type run kind merge and the frozen card
-- of a resolve run. Not here (E4e): author_autopilot.last_action merge —
-- nothing records that action before the autopilot's merge step exists.
-- The user columns carry no foreign key, like 64's: a key would lock the
-- user table.
--
-- Locks: the foreign keys take the decisions, the configurations and the
-- eval reports SHARE ROW EXCLUSIVE; they are taken up front, NOWAIT, like
-- 28-67, so a writer holding one makes the file fail at once and the next
-- start retries it whole. The decision table is empty until E4d inserts a
-- decision, so the key on it validates nothing.

SET LOCAL lock_timeout = '5s';

LOCK TABLE public.author_entity_merge_decision, public.author_llm_config, public.author_llm_eval_report
    IN SHARE ROW EXCLUSIVE MODE NOWAIT;

CREATE TABLE public.author_entity_merge_registration (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_version         text   NOT NULL REFERENCES public.author_llm_config (version) ON DELETE RESTRICT,
    kind                   text   NOT NULL,
    evidence_report_id     bigint NOT NULL,
    evidence_report_sha256 bytea  NOT NULL,
    gate                   text   NOT NULL,
    registered_by_user_id  bigint,
    registered_at          timestamptz NOT NULL DEFAULT now(),
    withdrawn_at           timestamptz,
    withdrawn_by_user_id   bigint,
    CONSTRAINT author_entity_merge_registration_key UNIQUE (config_version, kind),
    -- The report is cited by id and digest together: a registration can
    -- never name a report it did not read.
    CONSTRAINT author_entity_merge_registration_report_fkey
        FOREIGN KEY (evidence_report_id, evidence_report_sha256)
        REFERENCES public.author_llm_eval_report (id, report_sha256) ON DELETE RESTRICT,
    CONSTRAINT author_entity_merge_registration_kind_check CHECK (kind IN ('swap', 'initials', 'translit', 'bucket')),
    CONSTRAINT author_entity_merge_registration_gate_check CHECK (gate = 'judge_consensus'),
    CONSTRAINT author_entity_merge_registration_sha_check CHECK (octet_length(evidence_report_sha256) = 32),
    CONSTRAINT author_entity_merge_registration_withdrawn_check
        CHECK (withdrawn_at IS NOT NULL OR withdrawn_by_user_id IS NULL)
);

CREATE TABLE public.author_entity_merge_script_block (
    registration_id    bigint NOT NULL REFERENCES public.author_entity_merge_registration (id) ON DELETE RESTRICT,
    script             text   NOT NULL,
    blocked_at         timestamptz NOT NULL DEFAULT now(),
    blocked_by_user_id bigint,
    CONSTRAINT author_entity_merge_script_block_pkey PRIMARY KEY (registration_id, script),
    CONSTRAINT author_entity_merge_script_block_script_check CHECK (script IN ('Cyrl', 'Latn', 'Cyrl-Latn'))
);

-- A registration is never deleted and changes only by its withdrawal,
-- once; a block never changes.
CREATE TRIGGER author_entity_merge_registration_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_registration
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard('withdrawn_at', 'withdrawn_by_user_id');
CREATE TRIGGER author_entity_merge_script_block_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_script_block
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard();

-- Registrations and blocks are build input.
CREATE TRIGGER author_entity_merge_registration_entity_input_insert
    AFTER INSERT ON public.author_entity_merge_registration
    REFERENCING NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
CREATE TRIGGER author_entity_merge_registration_entity_input_update
    AFTER UPDATE ON public.author_entity_merge_registration
    REFERENCING OLD TABLE AS previous NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
CREATE TRIGGER author_entity_merge_script_block_entity_input_insert
    AFTER INSERT ON public.author_entity_merge_script_block
    REFERENCING NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();

ALTER TABLE public.author_entity_merge_decision
    ADD CONSTRAINT author_entity_merge_decision_config_fkey
        FOREIGN KEY (config_version) REFERENCES public.author_llm_config (version) ON DELETE RESTRICT,
    ADD CONSTRAINT author_entity_merge_decision_registration_fkey
        FOREIGN KEY (registration_id) REFERENCES public.author_entity_merge_registration (id) ON DELETE RESTRICT;

-- The function's body names the LLM tables; validating it at creation would
-- take them ACCESS SHARE and wait for a writer holding them. It is checked
-- at its first call instead (the adjudication insert and its trigger).
SET LOCAL check_function_bodies = off;

-- A contested accept of a merge eval: a census or holdout item (item set
-- holdout, merge candidate digest) that in some merge eval run both
-- production participants answered same (first answers) and whose judges'
-- first answers are not one shared, non-refused answer — the gate's
-- "no gold".
CREATE FUNCTION public.author_llm_eval_item_contested(item bigint) RETURNS boolean
    LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.author_llm_eval_item e
        JOIN public.author_llm_run r ON r.kind = 'eval' AND r.mode LIKE 'merge%'
        WHERE e.id = item AND e.item_set = 'holdout' AND e.extractor_version = 'e4-cand-v2'
            AND (SELECT count(DISTINCT j.slot) FROM public.author_llm_job j
                 JOIN public.author_llm_attempt a ON a.id = j.answer_attempt_id
                 WHERE j.run_id = r.id AND j.eval_item_id = e.id AND j.purpose = 'eval_candidate'
                     AND j.repeat_no = 0 AND j.status = 'answered' AND NOT coalesce(a.refused, false)
                     AND a.canonical_sha256 = sha256(convert_to('{"answer":"same"}', 'UTF8'))) = 2
            AND NOT coalesce((SELECT count(*) = 2 AND count(DISTINCT a.canonical_sha256) = 1
                                  AND bool_and(NOT coalesce(a.refused, false))
                              FROM public.author_llm_job j
                              JOIN public.author_llm_attempt a ON a.id = j.answer_attempt_id
                              WHERE j.run_id = r.id AND j.eval_item_id = e.id AND j.purpose = 'eval_judge'
                                  AND j.repeat_no = 0 AND j.status = 'answered'), false))
$$;

-- Only an adversarial suite item or a contested accept is adjudicated.
CREATE OR REPLACE FUNCTION public.author_llm_eval_adjudication_adversarial() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.author_llm_eval_item
                   WHERE id = NEW.eval_item_id AND item_set = 'adversarial')
       AND NOT public.author_llm_eval_item_contested(NEW.eval_item_id) THEN
        RAISE EXCEPTION 'eval item % is neither an adversarial suite item nor a contested accept', NEW.eval_item_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;
