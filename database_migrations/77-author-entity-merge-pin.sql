-- 77: the hand join (E4o). An administrator pins two entities as one
-- person; every build joins them after the decisions and keeps doing so
-- across rebuilds and archives, until the pin is revoked. A pin never
-- overrides a veto.
--
--   * author_entity_merge_pin — one pin: who registered it, a note, and its
--     revoke (once).
--   * author_entity_merge_pin_member — each side's raw fingerprints at
--     registration: the fingerprint rows of the side's entity, or the
--     fingerprints the administrator named. A credit of such a fingerprint
--     joins with its side in every later build.
--
-- History like the vetoes': a pin is never deleted and changes only by its
-- revoke; members never change. Pins are build input: a change marks the
-- autopilot.

CREATE TABLE public.author_entity_merge_pin (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note               text   NOT NULL DEFAULT '',
    created_at         timestamptz NOT NULL DEFAULT now(),
    created_by_user_id bigint,
    revoked_at         timestamptz,
    revoked_by_user_id bigint,
    CONSTRAINT author_entity_merge_pin_note_check CHECK (char_length(note) <= 500),
    CONSTRAINT author_entity_merge_pin_revoked_check CHECK (revoked_at IS NOT NULL OR revoked_by_user_id IS NULL)
);

CREATE TABLE public.author_entity_merge_pin_member (
    pin_id             bigint NOT NULL REFERENCES public.author_entity_merge_pin (id) ON DELETE RESTRICT,
    side               text   NOT NULL,
    source_fingerprint bytea  NOT NULL,
    CONSTRAINT author_entity_merge_pin_member_pkey PRIMARY KEY (pin_id, side, source_fingerprint),
    CONSTRAINT author_entity_merge_pin_member_side_check CHECK (side IN ('a', 'b'))
);

CREATE TRIGGER author_entity_merge_pin_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_pin
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard('revoked_at', 'revoked_by_user_id');
CREATE TRIGGER author_entity_merge_pin_member_history
    BEFORE UPDATE OR DELETE ON public.author_entity_merge_pin_member
    FOR EACH ROW EXECUTE FUNCTION public.author_entity_merge_history_guard();

-- Pins are build input. Their members are written in the same transaction
-- as their row, which marks already.
CREATE TRIGGER author_entity_merge_pin_entity_input_insert
    AFTER INSERT ON public.author_entity_merge_pin
    REFERENCING NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
CREATE TRIGGER author_entity_merge_pin_entity_input_update
    AFTER UPDATE ON public.author_entity_merge_pin
    REFERENCING OLD TABLE AS previous NEW TABLE AS changed
    FOR EACH STATEMENT EXECUTE FUNCTION public.author_autopilot_mark();
