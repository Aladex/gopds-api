-- 67: a human adjudication of an adversarial suite item (E4c-2b-0). The
-- merge eval's namesake suite labels every item "different" (a different
-- patronymic), and that label is noisy on this catalog: a wrong patronymic
-- in one source is common. An administrator reads a suite item the
-- production rule accepted and labels it same, different or unclear; the
-- suite gate then fails a stratum on every accept labeled different or
-- not labeled at all.
--
-- History is kept: every label is a new row, the latest row of an item is
-- its current label, and no row is ever changed or deleted. Only an item of
-- the adversarial set can be labeled (a trigger refuses any other).
--
-- Locks: the new table's foreign key takes the eval item table SHARE ROW
-- EXCLUSIVE; it is taken up front, NOWAIT, like 28-66, so a worker holding
-- it makes the file fail at once and the next start retries it whole.

SET LOCAL lock_timeout = '5s';

LOCK TABLE public.author_llm_eval_item IN SHARE ROW EXCLUSIVE MODE NOWAIT;

CREATE TABLE public.author_llm_eval_adjudication (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eval_item_id   BIGINT NOT NULL REFERENCES public.author_llm_eval_item (id) ON DELETE RESTRICT,
    label          TEXT NOT NULL,
    note           TEXT NOT NULL DEFAULT '',
    adjudicated_by TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT author_llm_eval_adjudication_label_check CHECK (label IN ('same', 'different', 'unclear')),
    CONSTRAINT author_llm_eval_adjudication_note_check CHECK (length(note) <= 2000),
    CONSTRAINT author_llm_eval_adjudication_by_check CHECK (adjudicated_by <> '')
);

CREATE INDEX author_llm_eval_adjudication_item_idx
    ON public.author_llm_eval_adjudication (eval_item_id, id DESC);

CREATE TRIGGER author_llm_eval_adjudication_immutable
    BEFORE UPDATE OR DELETE ON public.author_llm_eval_adjudication
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_mutation();

-- Only an adversarial suite item is adjudicated.
CREATE FUNCTION public.author_llm_eval_adjudication_adversarial() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.author_llm_eval_item
                   WHERE id = NEW.eval_item_id AND item_set = 'adversarial') THEN
        RAISE EXCEPTION 'eval item % is not an adversarial suite item', NEW.eval_item_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER author_llm_eval_adjudication_adversarial
    BEFORE INSERT ON public.author_llm_eval_adjudication
    FOR EACH ROW EXECUTE FUNCTION public.author_llm_eval_adjudication_adversarial();
