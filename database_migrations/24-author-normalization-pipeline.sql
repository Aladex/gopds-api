CREATE FUNCTION public.book_contributor_credit_selection_record() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW IS NOT DISTINCT FROM OLD THEN
        RETURN NULL;
    END IF;
    INSERT INTO public.book_contributor_credit_selection_audit
        (credit_id, previous_state, previous_result_id, state, result_id, basis, override_id,
         policy_version, unresolved_reason, decided_by_user_id)
    VALUES
        (NEW.credit_id,
         CASE WHEN TG_OP = 'UPDATE' THEN OLD.state END,
         CASE WHEN TG_OP = 'UPDATE' THEN OLD.result_id END,
         NEW.state, NEW.result_id, NEW.basis, NEW.override_id,
         NEW.policy_version, NEW.unresolved_reason, NEW.decided_by_user_id);
    RETURN NULL;
END
$$;

CREATE TRIGGER book_contributor_credit_selection_audited
    AFTER INSERT OR UPDATE ON public.book_contributor_credit_selection
    FOR EACH ROW EXECUTE FUNCTION public.book_contributor_credit_selection_record();

-- The local normalization queue: one job per normalization key, shared by all
-- author credits with that input. Lease columns carry the same names and
-- rules as author_metadata_run_item.
CREATE TABLE public.contributor_normalization_job (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    normalization_key  BYTEA NOT NULL,
    source_fingerprint BYTEA NOT NULL,
    extractor_version  TEXT NOT NULL,
    normalizer_version TEXT NOT NULL,
    status             TEXT NOT NULL DEFAULT 'pending',
    result_id          BIGINT,
    last_error_class   TEXT,
    lease_owner        UUID,
    lease_expires_at   TIMESTAMPTZ,
    attempt_count      INTEGER NOT NULL DEFAULT 0,
    next_attempt_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at        TIMESTAMPTZ,

    CONSTRAINT contributor_normalization_job_key
        UNIQUE (normalization_key),
    -- The job's result is the result of the job's own key.
    CONSTRAINT contributor_normalization_job_result_fkey
        FOREIGN KEY (result_id, normalization_key)
        REFERENCES public.contributor_normalization_result (id, normalization_key) ON DELETE RESTRICT,
    CONSTRAINT contributor_normalization_job_key_check
        CHECK (octet_length(normalization_key) = 32 AND octet_length(source_fingerprint) = 32),
    CONSTRAINT contributor_normalization_job_versions_check
        CHECK (extractor_version ~ '^[^[:space:]](.*[^[:space:]])?$'
               AND normalizer_version ~ '^[^[:space:]](.*[^[:space:]])?$'),
    CONSTRAINT contributor_normalization_job_status_check
        CHECK (status IN ('pending', 'completed', 'failed')),
    CONSTRAINT contributor_normalization_job_outcome_check
        CHECK (CASE status
                   WHEN 'completed' THEN result_id IS NOT NULL
                   WHEN 'failed' THEN result_id IS NULL AND last_error_class IS NOT NULL
                   ELSE result_id IS NULL
               END),
    CONSTRAINT contributor_normalization_job_error_class_check
        CHECK (last_error_class IS NULL OR last_error_class ~ '^[a-z][a-z0-9_]{0,63}$'),
    CONSTRAINT contributor_normalization_job_finished_check
        CHECK ((status = 'pending') = (finished_at IS NULL)),
    CONSTRAINT contributor_normalization_job_lease_pair_check
        CHECK ((lease_owner IS NULL) = (lease_expires_at IS NULL)),
    CONSTRAINT contributor_normalization_job_lease_terminal_check
        CHECK (status = 'pending' OR lease_owner IS NULL),
    CONSTRAINT contributor_normalization_job_attempt_count_check
        CHECK (attempt_count >= 0)
);

CREATE INDEX contributor_normalization_job_claim_idx
    ON public.contributor_normalization_job (next_attempt_at, id)
    WHERE status = 'pending';

