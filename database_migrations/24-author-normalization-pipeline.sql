-- Where one author credit stands. Every current author credit ends in exactly
-- one state:
--   selected   — a result is selected, automatically (registered class) or by
--                a credit/fingerprint override;
--   invalid    — the result is invalid (malformed source);
--   unresolved — closed reason, optionally with the proposal it rests on;
--   review     — an open review item decides it, optionally with a proposal.
-- Rows change as decisions are made; every change is appended to the audit by
-- trigger, and rows are never deleted.
CREATE TABLE public.book_contributor_credit_selection (
    credit_id          BIGINT PRIMARY KEY,
    source_fingerprint BYTEA NOT NULL,
    credit_role        TEXT NOT NULL DEFAULT 'author',
    state              TEXT NOT NULL,
    result_id          BIGINT,
    basis              TEXT,
    override_id        BIGINT,
    policy_version     TEXT,
    unresolved_reason  TEXT,
    -- NULL for a decision of the pipeline itself.
    decided_by_user_id BIGINT,
    decided_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT book_contributor_credit_selection_credit_fkey
        FOREIGN KEY (credit_id, source_fingerprint, credit_role)
        REFERENCES public.book_contributor_credit (id, source_fingerprint, role) ON DELETE RESTRICT,
    CONSTRAINT book_contributor_credit_selection_result_fkey
        FOREIGN KEY (result_id, source_fingerprint)
        REFERENCES public.contributor_normalization_result (id, source_fingerprint) ON DELETE RESTRICT,
    CONSTRAINT book_contributor_credit_selection_override_fkey
        FOREIGN KEY (override_id, result_id)
        REFERENCES public.contributor_manual_override (id, result_id) ON DELETE RESTRICT,
    CONSTRAINT book_contributor_credit_selection_role_check
        CHECK (credit_role = 'author'),
    CONSTRAINT book_contributor_credit_selection_state_check
        CHECK (state IN ('selected', 'invalid', 'unresolved', 'review')),
    CONSTRAINT book_contributor_credit_selection_basis_check
        CHECK (basis IS NULL OR basis IN ('automatic', 'fingerprint_override', 'credit_override')),
    CONSTRAINT book_contributor_credit_selection_reason_check
        CHECK (unresolved_reason IS NULL
               OR unresolved_reason IN ('policy_not_registered', 'normalizer_failed', 'review_left_unresolved')),
    -- What each state requires and forbids.
    CONSTRAINT book_contributor_credit_selection_shape_check
        CHECK (CASE state
                   WHEN 'selected' THEN result_id IS NOT NULL AND basis IS NOT NULL AND unresolved_reason IS NULL
                   WHEN 'invalid' THEN result_id IS NOT NULL AND basis IS NULL AND unresolved_reason IS NULL
                   WHEN 'unresolved' THEN basis IS NULL AND unresolved_reason IS NOT NULL
                   ELSE basis IS NULL AND unresolved_reason IS NULL
               END),
    -- Automatic selection names the policy it was allowed by; an override
    -- selection names the override.
    CONSTRAINT book_contributor_credit_selection_basis_shape_check
        CHECK (CASE basis
                   WHEN 'automatic' THEN override_id IS NULL AND policy_version IS NOT NULL
                   WHEN 'fingerprint_override' THEN override_id IS NOT NULL AND policy_version IS NULL
                   WHEN 'credit_override' THEN override_id IS NOT NULL AND policy_version IS NULL
                   ELSE override_id IS NULL AND policy_version IS NULL
               END),
    CONSTRAINT book_contributor_credit_selection_actor_check
        CHECK (decided_by_user_id IS NULL OR decided_by_user_id > 0)
);

CREATE INDEX book_contributor_credit_selection_state_idx
    ON public.book_contributor_credit_selection (state, unresolved_reason);

-- Rules a CHECK cannot see because they read other rows. It runs as an AFTER
-- constraint trigger, so the row's own CHECKs and foreign keys report first
-- and this only judges rows that are well-formed on their own.
CREATE FUNCTION public.book_contributor_credit_selection_check() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    res public.contributor_normalization_result%ROWTYPE;
    ovr public.contributor_manual_override%ROWTYPE;
    credit_extractor text;
BEGIN
    IF NEW.result_id IS NULL THEN
        RETURN NULL;
    END IF;
    SELECT * INTO res FROM public.contributor_normalization_result WHERE id = NEW.result_id;

    IF NEW.state = 'invalid' AND res.status <> 'invalid' THEN
        RAISE EXCEPTION 'book_contributor_credit_selection: an invalid credit must rest on an invalid result'
            USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.state = 'selected' AND res.status = 'invalid' THEN
        RAISE EXCEPTION 'book_contributor_credit_selection: an invalid result cannot be selected'
            USING ERRCODE = 'check_violation';
    END IF;

    -- An automatic result is about one normalization input: the credit's own
    -- extractor version, not merely the same fingerprint.
    IF res.method <> 'manual' THEN
        SELECT s.extractor_version INTO credit_extractor
        FROM public.book_contributor_credit c
        JOIN public.book_metadata_snapshot s ON s.id = c.snapshot_id
        WHERE c.id = NEW.credit_id;
        IF credit_extractor IS DISTINCT FROM res.extractor_version THEN
            RAISE EXCEPTION 'book_contributor_credit_selection: result extractor version differs from the credit''s snapshot'
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    IF NEW.basis = 'automatic' THEN
        IF res.method = 'manual' THEN
            RAISE EXCEPTION 'book_contributor_credit_selection: a manual result is selected through its override'
                USING ERRCODE = 'check_violation';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM public.author_acceptance_class a
            WHERE a.policy_version = NEW.policy_version
              AND a.decision_class = res.decision_class
              AND a.config_version = res.normalizer_version) THEN
            RAISE EXCEPTION 'book_contributor_credit_selection: decision class is not registered in the acceptance policy'
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF NEW.basis IS NOT NULL THEN
        SELECT * INTO ovr FROM public.contributor_manual_override WHERE id = NEW.override_id;
        IF NEW.basis = 'credit_override' AND ovr.scope_credit_id IS DISTINCT FROM NEW.credit_id THEN
            RAISE EXCEPTION 'book_contributor_credit_selection: a credit override applies only to its own credit'
                USING ERRCODE = 'check_violation';
        END IF;
        IF NEW.basis = 'fingerprint_override' AND ovr.scope_fingerprint IS NULL THEN
            RAISE EXCEPTION 'book_contributor_credit_selection: basis fingerprint_override needs a fingerprint-scoped override'
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NULL;
END
$$;

CREATE CONSTRAINT TRIGGER book_contributor_credit_selection_consistency
    AFTER INSERT OR UPDATE ON public.book_contributor_credit_selection
    FOR EACH ROW EXECUTE FUNCTION public.book_contributor_credit_selection_check();

