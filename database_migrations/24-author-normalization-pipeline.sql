-- Author normalization pipeline: immutable normalization results, the
-- per-credit resolution (selected / invalid / unresolved / open review) with an
-- append-only audit, immutable manual overrides, the local-normalization queue,
-- the manual review queue and the acceptance-policy classes.
--
-- There is no LLM stream in this project: no LLM job, attempt or provider batch
-- table. The result method enum still carries 'llm' so a later LLM project
-- needs no enum migration.
--
-- Cross-table "same source" rules are composite foreign keys onto
-- (id, source_fingerprint[, role]); the remaining rules that need a lookup live
-- in one consistency trigger on the resolution table.

SET LOCAL lock_timeout = '5s';

-- Target of the composite foreign keys below: a resolution, override or review
-- item names a credit together with its fingerprint and role, so it cannot
-- pair a credit with a result computed from another source, and only author
-- credits enter the pipeline.
ALTER TABLE public.book_contributor_credit
    ADD CONSTRAINT book_contributor_credit_id_fingerprint_role_key
        UNIQUE (id, source_fingerprint, role);

-- Shared guard for rows that are mutable while open and frozen once
-- finished_at is set.
CREATE FUNCTION public.author_metadata_reject_finished() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF (to_jsonb(OLD) ->> 'finished_at') IS NOT NULL THEN
        RAISE EXCEPTION 'rows of % are immutable once finished', TG_TABLE_NAME
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END
$$;

-- An acceptance-policy class: automatic selection is allowed only for a
-- registered (policy_version, decision_class). Registration is a later,
-- separate step; nothing here seeds a row, so the production policy is empty
-- and an empty policy means zero autoaccept.
CREATE TABLE public.author_acceptance_class (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_version         TEXT NOT NULL,
    decision_class         TEXT NOT NULL,
    -- The normalizer configuration the evidence was measured on.
    config_version         TEXT NOT NULL,
    -- Raw SHA-256 of the immutable evidence/eval report.
    evidence_report_sha256 BYTEA NOT NULL,
    registered_by_user_id  BIGINT NOT NULL,
    registered_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT author_acceptance_class_key
        UNIQUE (policy_version, decision_class),
    CONSTRAINT author_acceptance_class_policy_version_check
        CHECK (policy_version ~ '^[^[:space:]](.*[^[:space:]])?$'),
    CONSTRAINT author_acceptance_class_decision_class_check
        CHECK (decision_class ~ '^[a-z][a-z0-9_.]{0,63}$'),
    CONSTRAINT author_acceptance_class_config_version_check
        CHECK (config_version ~ '^[^[:space:]](.*[^[:space:]])?$'),
    CONSTRAINT author_acceptance_class_evidence_check
        CHECK (octet_length(evidence_report_sha256) = 32),
    CONSTRAINT author_acceptance_class_actor_check
        CHECK (registered_by_user_id > 0)
);

CREATE TRIGGER author_acceptance_class_immutable
    BEFORE UPDATE OR DELETE ON public.author_acceptance_class
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_mutation();

-- The lexical result for one normalization input. Not a person and not a
-- canonical author. Immutable: a correction is a new row.
CREATE TABLE public.contributor_normalization_result (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_fingerprint    BYTEA NOT NULL,
    -- Automatic results only: SHA-256 over fingerprint and both versions.
    normalization_key     BYTEA,
    extractor_version     TEXT,
    normalizer_version    TEXT,
    result_schema_version TEXT NOT NULL,
    method                TEXT NOT NULL,
    kind                  TEXT NOT NULL,
    status                TEXT NOT NULL,
    decision_class        TEXT,
    given_name            TEXT,
    additional_names      TEXT[] NOT NULL DEFAULT '{}',
    family_name           TEXT,
    nickname              TEXT,
    prefix                TEXT,
    suffix                TEXT,
    display_name          TEXT,
    sort_name             TEXT,
    search_key            TEXT,
    script                TEXT,
    quality_flags         TEXT[] NOT NULL DEFAULT '{}',
    -- The admin who wrote a manual result. Audit, so no foreign key: the row
    -- is immutable and must outlive the account.
    created_by_user_id    BIGINT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Targets of composite foreign keys: a pointer to a result always names
    -- the source it was computed from (and, for overrides, its method; for
    -- jobs, its key).
    CONSTRAINT contributor_normalization_result_id_fingerprint_key
        UNIQUE (id, source_fingerprint),
    CONSTRAINT contributor_normalization_result_id_fingerprint_method_key
        UNIQUE (id, source_fingerprint, method),
    CONSTRAINT contributor_normalization_result_id_key_key
        UNIQUE (id, normalization_key),
    CONSTRAINT contributor_normalization_result_method_check
        CHECK (method IN ('structured', 'rules', 'llm', 'manual')),
    CONSTRAINT contributor_normalization_result_kind_check
        CHECK (kind IN ('person', 'collective', 'unknown', 'malformed')),
    CONSTRAINT contributor_normalization_result_status_check
        CHECK (status IN ('normalized', 'unresolved', 'invalid')),
    -- Empty or punctuation garbage is malformed and never a valid name.
    CONSTRAINT contributor_normalization_result_malformed_check
        CHECK (kind <> 'malformed' OR status = 'invalid'),
    CONSTRAINT contributor_normalization_result_fingerprint_check
        CHECK (octet_length(source_fingerprint) = 32),
    -- Automatic results carry their key, both exact versions and a decision
    -- class, and no actor; a manual result carries an actor and none of the
    -- automatic inputs, so a normalizer version change never invalidates it.
    -- coalesce: a comparison with NULL must fail the check, not pass it.
    CONSTRAINT contributor_normalization_result_provenance_check
        CHECK (coalesce(CASE method
                   WHEN 'manual' THEN num_nonnulls(normalization_key, extractor_version, normalizer_version) = 0
                                      AND created_by_user_id > 0
                   ELSE octet_length(normalization_key) = 32
                        AND extractor_version ~ '^[^[:space:]](.*[^[:space:]])?$'
                        AND normalizer_version ~ '^[^[:space:]](.*[^[:space:]])?$'
                        AND created_by_user_id IS NULL
                        AND decision_class IS NOT NULL
               END, false)),
    CONSTRAINT contributor_normalization_result_schema_version_check
        CHECK (result_schema_version ~ '^[^[:space:]](.*[^[:space:]])?$'),
    CONSTRAINT contributor_normalization_result_decision_class_check
        CHECK (decision_class IS NULL OR decision_class ~ '^[a-z][a-z0-9_.]{0,63}$'),
    -- ISO 15924 code, or mixed when several letter scripts occur.
    CONSTRAINT contributor_normalization_result_script_check
        CHECK (script IS NULL OR script ~ '^[A-Z][a-z]{3}$' OR script = 'mixed'),
    -- A normalized result has a display name and a search key.
    CONSTRAINT contributor_normalization_result_normalized_check
        CHECK (status <> 'normalized' OR coalesce(display_name <> '' AND search_key <> '', false)),
    CONSTRAINT contributor_normalization_result_arrays_check
        CHECK (array_position(additional_names, NULL) IS NULL
               AND array_position(quality_flags, NULL) IS NULL)
);

