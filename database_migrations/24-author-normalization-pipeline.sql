    CONSTRAINT contributor_review_item_decision_class_check
        CHECK (decision_class IS NULL OR decision_class ~ '^[a-z][a-z0-9_.]{0,63}$'),
    CONSTRAINT contributor_review_item_status_check
        CHECK (status IN ('open', 'closed')),
    CONSTRAINT contributor_review_item_resolution_check
        CHECK (resolution IS NULL
               OR resolution IN ('accepted', 'edited', 'classified', 'left_unresolved', 'retried')),
    -- Open: nothing decided. Closed: a resolution, a time and, except for a
    -- retry handed back to the normalizer, the admin who made it.
    CONSTRAINT contributor_review_item_closed_check
        CHECK (coalesce(CASE status
                   WHEN 'open' THEN num_nonnulls(resolution, resolution_result_id, resolved_by_user_id, finished_at) = 0
                   ELSE resolution IS NOT NULL AND finished_at IS NOT NULL AND finished_at >= created_at
                        AND (resolved_by_user_id > 0 OR resolution = 'retried')
               END, false)),
    CONSTRAINT contributor_review_item_credit_fkey
        FOREIGN KEY (scope_credit_id, source_fingerprint, credit_role)
        REFERENCES public.book_contributor_credit (id, source_fingerprint, role) ON DELETE RESTRICT,
    CONSTRAINT contributor_review_item_proposal_fkey
        FOREIGN KEY (proposal_result_id, source_fingerprint)
        REFERENCES public.contributor_normalization_result (id, source_fingerprint) ON DELETE RESTRICT,
    CONSTRAINT contributor_review_item_resolution_result_fkey
        FOREIGN KEY (resolution_result_id, source_fingerprint)
        REFERENCES public.contributor_normalization_result (id, source_fingerprint) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX contributor_review_item_one_open_per_credit
    ON public.contributor_review_item (scope_credit_id, reason)
    WHERE status = 'open' AND scope_credit_id IS NOT NULL;

CREATE UNIQUE INDEX contributor_review_item_one_open_per_fingerprint
    ON public.contributor_review_item (scope_fingerprint, reason)
    WHERE status = 'open' AND scope_fingerprint IS NOT NULL;

-- Stable review pagination by (created_at, id).
CREATE INDEX contributor_review_item_open_page_idx
    ON public.contributor_review_item (created_at, id)
    WHERE status = 'open';

CREATE TRIGGER contributor_review_item_immutable
    BEFORE UPDATE OR DELETE ON public.contributor_review_item
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_mutation(
        'status', 'resolution', 'resolution_result_id', 'resolved_by_user_id', 'finished_at');

CREATE TRIGGER contributor_review_item_closed
    BEFORE UPDATE ON public.contributor_review_item
    FOR EACH ROW EXECUTE FUNCTION public.author_metadata_reject_finished();
