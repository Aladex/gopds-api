    CONSTRAINT contributor_review_item_scope_check
        CHECK (num_nonnulls(scope_credit_id, scope_fingerprint) = 1),
    CONSTRAINT contributor_review_item_credit_check
        CHECK (scope_credit_id IS NULL OR scope_credit_id > 0),
