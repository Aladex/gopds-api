package models

import "testing"

// A book list writes an author «Имя Фамилия»: only a Cyrillic patronymic
// between the given and the family name is dropped, and every other middle
// part stays.
func TestShortAuthorNameDropsOnlyAPatronymic(t *testing.T) {
	cases := []struct{ name, want string }{
		// Patronymics: male, female, -ична, Ukrainian.
		{"Владимир Дмитриевич Михайлов", "Владимир Михайлов"},
		{"Мария Васильевна Семенова", "Мария Семенова"},
		{"Михаил Павлович Игнатов", "Михаил Игнатов"},
		{"Елена Владимировна Хаецкая", "Елена Хаецкая"},
		{"Павло Архипович Загребельний", "Павло Загребельний"},
		{"Людмила Никитична Иванова", "Людмила Иванова"},
		{"Вера Ильинична Петрова", "Вера Петрова"},
		{"Леся Андріївна Українка", "Леся Українка"},
		{"Оксана Іванівна Забужко", "Оксана Забужко"},
		{"Владимир Ильич Ленин", "Владимир Ленин"},
		{"Иван Кузьмич Андрощук", "Иван Андрощук"},
		{"Сергей Никитич Ашихманов", "Сергей Ашихманов"},
		{"Алексей Савич Корюков", "Алексей Корюков"},
		{"Михаил Евграфович Салтыков-Щедрин", "Михаил Салтыков-Щедрин"},
		{"ВЛАДИМИР ДМИТРИЕВИЧ МИХАЙЛОВ", "ВЛАДИМИР МИХАЙЛОВ"},
		// Spaces of any kind count as one.
		{"  Мария\u00a0Васильевна   Семенова ", "Мария Семенова"},
		// Other middle parts stay.
		{"Урсула Крёбер Ле Гуин", "Урсула Крёбер Ле Гуин"},
		{"Джордж Р. Р. Мартин", "Джордж Р. Р. Мартин"},
		{"Артур Конан Дойл", "Артур Конан Дойл"},
		{"Эрнст Теодор Амадей Гофман", "Эрнст Теодор Амадей Гофман"},
		{"Архимандрит Иоанн (Крестьянкин)", "Архимандрит Иоанн (Крестьянкин)"},
		{"Иван Петрович (Сидоров)", "Иван Петрович (Сидоров)"},
		{"Аркадий и Борис Стругацкие", "Аркадий и Борис Стругацкие"},
		{"Agatha Christie", "Agatha Christie"},
		{"Mary Ivanovich Smith", "Mary Ivanovich Smith"},
		{"Анна Ahmetovna Ли", "Анна Ahmetovna Ли"},
		// Two words, one word, nothing.
		{"Борис Акунин", "Борис Акунин"},
		{"Бажович Иван", "Бажович Иван"},
		{"Сапфо", "Сапфо"},
		{"", ""},
		// Too short to be a patronymic.
		{"Иван Бич Петров", "Иван Бич Петров"},
		{"Анна Вич Ли", "Анна Вич Ли"},
		{"Анна Ична Ли", "Анна Ична Ли"},
		// A bare -ич ends family names too.
		{"Синтия Лейтич Смит", "Синтия Лейтич Смит"},
		{"Сергей Милич Рафальский", "Сергей Милич Рафальский"},
		// A patronymic not between a given and a family name.
		{"Иван Иванович", "Иван Иванович"},
		{"Толстой Лев Николаевич", "Толстой Лев Николаевич"},
		{"Анна Петровна Ивановна Смит", "Анна Петровна Ивановна Смит"},
	}
	for _, c := range cases {
		if got := ShortAuthorName(c.name); got != c.want {
			t.Errorf("ShortAuthorName(%q) = %q, want %q", c.name, got, c.want)
		}
	}
}
