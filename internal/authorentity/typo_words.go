package authorentity

import (
	"bytes"
	_ "embed" // the frozen word table
	"fmt"
	"strconv"
	"strings"
	"sync"
)

// The frozen word table of the typo rule. The rule weighs how common a word
// is, and a decision applies only while its candidate exists, so counts read
// from the live catalog would let an unrelated new author take a candidate
// away and part a pair the model joined. The rule therefore reads only the two
// names and this table: a build gives one answer whatever the catalog does.
//
// Each line is a word and the level-0 sides holding it, in the family or the
// given place, whichever is more. Only words on typoWordFloor sides or more
// are listed. A word missing from the table is rare: one side.
//
// Regenerating the table is a new version of the rule. It may take candidates
// away, and their applied decisions lapse with them, or add new ones to ask:
//
//  1. go run ./cmd/author-typo-words -rule N+1 >
//     internal/authorentity/typo_words_vN+1.tsv, against a fresh prod copy;
//  2. point the embed below at the new file, delete the old one, and set
//     TypoRuleVersion and the checksum pinned in typo_words_test.go to the
//     new values: a table changed in place is a rule changed without a version;
//  3. simulate two passes on the copy and diff DecisionStates before release.

// TypoRuleVersion is the version of the typo rule and of its word table.
const TypoRuleVersion = 1

// typoWordFloor is the fewest sides of a listed word.
const typoWordFloor = 2

//go:embed typo_words_v1.tsv
var typoWordsFile string

// typoWordTable is the parsed table, read once on first use.
var typoWordTable = sync.OnceValue(func() map[string]int { return parseTypoWords(typoWordsFile) })

// parseTypoWords reads a table; a malformed embedded table is a broken build.
func parseTypoWords(file string) map[string]int {
	out := map[string]int{}
	for line := range strings.Lines(file) {
		line = strings.TrimSuffix(line, "\n")
		if strings.HasPrefix(line, "#") {
			continue
		}
		word, count, ok := strings.Cut(line, "\t")
		n, err := strconv.Atoi(count)
		if !ok || err != nil {
			panic(fmt.Sprintf("authorentity: bad typo word line %q", line))
		}
		out[word] = n
	}
	return out
}

// typoWordSides is how many sides the table gives a word.
func typoWordSides(word string) int {
	if n, ok := typoWordTable()[word]; ok {
		return n
	}
	return 1
}

// TypoWordCounts counts the words of the plan's level-0 sides, for
// RenderTypoWords. The build itself never counts.
func (p *Plan) TypoWordCounts() map[string]int {
	family, given := map[string]map[int]bool{}, map[string]map[int]bool{}
	add := func(slot map[string]map[int]bool, word string, root int) {
		if slot[word] == nil {
			slot[word] = map[int]bool{}
		}
		slot[word][root] = true
	}
	for _, root := range sortedKeys(p.cand.sides) {
		s := p.cand.sides[root]
		for _, k := range s.keys {
			if key := &p.cand.b.keys[k].key; typoKey(key) {
				add(family, key.family, s.root)
				add(given, key.given, s.root)
			}
		}
	}
	out := make(map[string]int, len(family)+len(given))
	for word, sides := range family {
		out[word] = len(sides)
	}
	for word, sides := range given {
		out[word] = max(out[word], len(sides))
	}
	return out
}

// RenderTypoWords writes the table of a rule version from word counts, in
// word order, so two renderings of one catalog are one file.
func RenderTypoWords(rule int, counts map[string]int) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, "# typo rule %d: word, sides. Generated by cmd/author-typo-words; a new table is a new rule version.\n", rule)
	for _, word := range sortedKeys(counts) {
		if counts[word] < typoWordFloor {
			continue
		}
		if word == "" || strings.ContainsAny(word, "\t\n") || word[0] == '#' {
			return nil, fmt.Errorf("authorentity: word %q cannot be written to the table", word)
		}
		fmt.Fprintf(&out, "%s\t%d\n", word, counts[word])
	}
	return out.Bytes(), nil
}
